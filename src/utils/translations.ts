/**
 * Smart translation function that checks if a string contains any of our target Telugu phrases,
 * translates them, and leaves English text completely untouched.
 */
export function translate(text: string, lang: LanguageCode): string {
  if (!text) return '';
  if (lang === 'te') return text;

  let result = text;
  
  // Try exact match first
  if (TRANSLATION_DICTIONARY[text]) {
    return TRANSLATION_DICTIONARY[text][lang];
  }

  // Try substring replacement for key phrases
  Object.keys(TRANSLATION_DICTIONARY).forEach((key) => {
    if (result.includes(key)) {
      result = result.replace(new RegExp(escapeRegExp(key), 'g'), TRANSLATION_DICTIONARY[key][lang]);
    }
  });

  return result;
}

function escapeRegExp(string: string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); // $& means the whole matched string
}
